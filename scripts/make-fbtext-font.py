#!/usr/bin/env python3
"""The font of oakmoss-fbtext (src/fbtext.c): DejaVu Sans Mono in 8x16 cells, one alpha byte
a pixel, ASCII 32-126, written as src/fbtext-font.h with the font's licence.

    scripts/make-fbtext-font.py

Needs Pillow and the DejaVu fonts (Debian fonts-dejavu-core), as make-charge-screens.py does:
run it in the Lima VM. The output is deterministic, so a re-run reproduces the header.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
LICENCE = "/usr/share/doc/fonts-dejavu-core/copyright"
CW, CH, SIZE, BASELINE = 8, 16, 13, 12   # 13 px: DejaVu Sans Mono's advance is 7.8 px


def main():
    font = ImageFont.truetype(FONT, SIZE)
    glyphs = []
    for c in range(32, 127):
        im = Image.new("L", (CW, CH), 0)
        ImageDraw.Draw(im).text((CW / 2, BASELINE), chr(c), font=font, fill=255, anchor="ms")
        glyphs.append(list(im.getdata()))
    licence = open(LICENCE).read().replace("*/", "* /").replace("/*", "/ *").rstrip("\n").split("\n")   # nothing that opens or ends a C comment
    out = os.path.join(ROOT, "src", "fbtext-font.h")
    with open(out, "w") as f:
        f.write("/*\n * Generated by scripts/make-fbtext-font.py: do not edit. DejaVu Sans Mono, "
                f"{SIZE} px in {CW}x{CH} cells,\n * one alpha byte a pixel, ASCII 32-126. "
                f"The font's licence ({LICENCE}):\n *\n")
        f.writelines(f" * {l}".rstrip() + "\n" for l in licence)
        f.write(" */\n")
        f.write(f"static const unsigned char font8x16[95][{CH}][{CW}] = {{\n")
        for c, g in zip(range(32, 127), glyphs):
            rows = ", ".join("{" + ",".join(str(v) for v in g[y * CW:(y + 1) * CW]) + "}" for y in range(CH))
            f.write(f"\t/* {c:3d} {chr(c) if c != 92 else 'backslash'} */ {{ {rows} }},\n")
        f.write("};\n")
    print(f"{out}: {len(glyphs)} glyphs, {CW}x{CH}, DejaVu Sans Mono {SIZE} px")


if __name__ == "__main__":
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    main()
